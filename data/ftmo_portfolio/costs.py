"""Cost engine: swap (time-varying), spread, commission, lot quantization.

Anchors (measured/specs, cross-validated):
  - US100.cash swap_long -662.4 pts -> -3.08 bps/night (matches broker capture)
  - USDJPY long +0.20 bps/night credit, short -1.63 bps/night
Method:
  - FX: swap_ann(t) = ratediff(t) - markup, markup calibrated on June-2026 specs
        vs June-2026 3m rates, held constant through history (regime-honest).
  - Index/metal: swap_long_ann(t) = -(r_ccy(t) + markup_L);
                 swap_short_ann(t) = +r_ccy(t) - markup_S.
  - Energy/softs: constant (specs snapshot); wide stress band (sign-flip tested).
  - Crypto: -30%/yr both sides (user-provided), stress +-50%.
Accrual: FX/metals 3x Wednesday; index/energy/softs 3x Friday; crypto 7/7.
"""
import numpy as np
import pandas as pd
import config as C

SPECS_PATH = C.DATA / "ftmo_research" / "ftmo_specs_full.csv"

# symbol mapping research-name -> specs ticker
TICKER = {"US100": "US100.cash", "UKOIL": "UKOIL.cash", "USOIL": "USOIL.cash",
          "COCOA": "COCOA.c", "COFFEE": "COFFEE.c", "SUGAR": "SUGAR.c",
          "COTTON": "COTTON.c", "SOYBEAN": "SOYBEAN.c", "WHEAT": "WHEAT.c"}

QUOTE_CCY = {  # profit currency of 1 unit move
    "EURUSD": "USD", "GBPUSD": "USD", "AUDUSD": "USD", "NZDUSD": "USD",
    "USDJPY": "JPY", "USDCHF": "CHF", "USDCAD": "CAD",
    "EURJPY": "JPY", "EURGBP": "GBP", "AUDJPY": "JPY",
}
BASE_NOTIONAL_CCY = {  # contract notional currency (margin ccy in specs)
    "EURUSD": "EUR", "GBPUSD": "GBP", "AUDUSD": "AUD", "NZDUSD": "NZD",
    "USDJPY": "USD", "USDCHF": "USD", "USDCAD": "USD",
    "EURJPY": "EUR", "EURGBP": "EUR", "AUDJPY": "AUD",
}
PAIR_LEGS = {  # (base, quote) for rate differential
    "EURUSD": ("EUR","USD"), "GBPUSD": ("GBP","USD"), "AUDUSD": ("AUD","USD"),
    "NZDUSD": ("NZD","USD"), "USDJPY": ("USD","JPY"), "USDCHF": ("USD","CHF"),
    "USDCAD": ("USD","CAD"), "EURJPY": ("EUR","JPY"), "EURGBP": ("EUR","GBP"),
    "AUDJPY": ("AUD","JPY"),
}
FIN_CCY = {"US500": "USD", "US100": "USD", "US30": "USD", "GER40": "EUR",
           "XAUUSD": "USD", "XAGUSD": "USD"}
TRIPLE_DAY = {}  # filled from specs; default Wed for FX/metals, Fri otherwise


def _load_specs():
    s = pd.read_csv(SPECS_PATH)
    s = s.set_index("ticker")
    return s


def swap_bps_per_night_today(symbol: str, price: float, usd_rate: dict) -> tuple:
    """(long_bps, short_bps) per night from specs points, at given price.
    usd_rate: dict ccy->USD conversion for JPY/CHF/... quote ccys (price of 1 unit in USD).
    Returns (nan, nan) if symbol not in specs."""
    s = _load_specs()
    t = TICKER.get(symbol, symbol)
    if t not in s.index:
        return (np.nan, np.nan)
    row = s.loc[t]
    digits = int(row["digits"])
    csize = float(str(row["contract_size"]).split()[0])
    point = 10.0 ** (-digits)
    # value of 1 point for 1 lot, in QUOTE currency:
    pt_val_quote = csize * point
    quote = QUOTE_CCY.get(symbol, "USD")
    fx = usd_rate.get(quote, 1.0)
    # notional in USD for 1 lot:
    if symbol in BASE_NOTIONAL_CCY:
        base = BASE_NOTIONAL_CCY[symbol]
        notional = csize * usd_rate.get(base, 1.0)
    else:
        notional = csize * price  # CFD: contract_size units of the index/commodity
        pt_val_quote = csize * point  # quote==USD for all CFDs here
    lb = float(row["swap_long"]) * pt_val_quote * fx
    sb = float(row["swap_short"]) * pt_val_quote * fx
    TRIPLE_DAY[symbol] = str(row.get("swap_3x_day", "Wednesday"))
    return (1e4 * lb / notional, 1e4 * sb / notional)


def build_swap_model(prices_today: dict, rates: pd.DataFrame,
                     asof: str = "2026-05-31") -> pd.DataFrame:
    """Calibrate markups; return per-symbol DataFrame:
       [kind, swap_long_bps_today, swap_short_bps_today, markup_L, markup_S, triple_day]
       markups in %/yr. Time series generated by swap_series()."""
    r0 = rates.ffill().loc[:asof].iloc[-1]
    usd_rate = prices_today.get("_usd_rate", {})
    rows = {}
    fx_markups = []
    for sym in C.FX:
        lb, sb = swap_bps_per_night_today(sym, prices_today.get(sym, np.nan), usd_rate)
        b, q = PAIR_LEGS[sym]
        diff = (r0[b] - r0[q])
        if np.isfinite(lb):
            mL = diff - lb * 365 / 100.0     # %/yr
            mS = -diff - sb * 365 / 100.0
            fx_markups.append((mL, mS))
            rows[sym] = dict(kind="fx", lb=lb, sb=sb, mL=mL, mS=mS,
                             triple=TRIPLE_DAY.get(sym, "Wednesday"), est=False)
    medL = float(np.median([m[0] for m in fx_markups]))
    medS = float(np.median([m[1] for m in fx_markups]))
    for sym in C.FX:                      # missing pairs -> median markup
        if sym not in rows:
            b, q = PAIR_LEGS[sym]
            diff = r0[b] - r0[q]
            rows[sym] = dict(kind="fx", lb=(diff - medL) * 100 / 365,
                             sb=(-diff - medS) * 100 / 365, mL=medL, mS=medS,
                             triple="Wednesday", est=True)
    # indices & metals: financing on ccy rate
    anchorL, anchorS = swap_bps_per_night_today("US100", prices_today["US100"], usd_rate)
    mL_idx = -anchorL * 365 / 100.0 - r0["USD"]   # markup over benchmark, long pays
    mS_idx = r0["USD"] - anchorS * 365 / 100.0    # short receives bench - markup
    for sym in C.INDICES:
        ccy = FIN_CCY[sym]
        lb, sb = swap_bps_per_night_today(sym, prices_today.get(sym, np.nan), usd_rate)
        est = not np.isfinite(lb)
        if est:
            lb = -(r0[ccy] + mL_idx) * 100 / 365
            sb = (r0[ccy] - mS_idx) * 100 / 365
        rows[sym] = dict(kind="index", lb=lb, sb=sb, mL=mL_idx, mS=mS_idx,
                         triple="Friday", est=est)
    for sym in C.METALS:
        lb, sb = swap_bps_per_night_today(sym, prices_today[sym], usd_rate)
        mL = -lb * 365 / 100 - r0["USD"]; mS = r0["USD"] - sb * 365 / 100
        rows[sym] = dict(kind="metal", lb=lb, sb=sb, mL=mL, mS=mS,
                         triple=TRIPLE_DAY.get(sym, "Wednesday"), est=False)
    for sym in C.ENERGY + C.SOFTS:        # constant snapshot
        lb, sb = swap_bps_per_night_today(sym, prices_today.get(sym, np.nan), usd_rate)
        rows[sym] = dict(kind="energy_soft", lb=lb, sb=sb, mL=np.nan, mS=np.nan,
                         triple="Friday", est=not np.isfinite(lb))
    for sym in C.CRYPTO:
        bps = C.CRYPTO_SWAP_ANNUAL / 365 * 1e4
        rows[sym] = dict(kind="crypto", lb=bps, sb=bps, mL=np.nan, mS=np.nan,
                         triple=None, est=False)
    df = pd.DataFrame(rows).T
    for c in ("lb","sb","mL","mS"):
        df[c] = df[c].astype(float)
    return df


def swap_series(symbol: str, model: pd.DataFrame, rates: pd.DataFrame,
                index: pd.DatetimeIndex) -> pd.DataFrame:
    """Daily (bps/night) long & short swap series aligned to index."""
    m = model.loc[symbol]
    r = rates.ffill().reindex(rates.index.union(index)).ffill().reindex(index)
    if m["kind"] == "fx":
        b, q = PAIR_LEGS[symbol]
        diff = r[b] - r[q]
        lb = (diff - m["mL"]) * 100 / 365
        sb = (-diff - m["mS"]) * 100 / 365
    elif m["kind"] in ("index", "metal"):
        ccy = FIN_CCY[symbol]
        lb = -(r[ccy] + m["mL"]) * 100 / 365
        sb = (r[ccy] - m["mS"]) * 100 / 365
    else:  # constant
        lb = pd.Series(m["lb"], index=index)
        sb = pd.Series(m["sb"], index=index)
    return pd.DataFrame({"long_bps": lb, "short_bps": sb}, index=index)


def swap_multiplier(dates: pd.DatetimeIndex, triple_day, crypto: bool=False) -> pd.Series:
    """Nights charged per trading day (1 normally, 3 on triple day).
    Crypto: 7 nights/week -> on a daily Mon-Fri grid use Mon=3 (Sat+Sun+Mon)."""
    wd = pd.Series(dates.dayofweek, index=dates)
    if crypto:
        return wd.map(lambda d: 3 if d == 0 else 1).astype(float)
    day = {"Monday":0,"Tuesday":1,"Wednesday":2,"Thursday":3,"Friday":4}.get(str(triple_day), 4)
    return wd.map(lambda d: 3 if d == day else 1).astype(float)


def commission_bps(symbol: str, price: float, usd_rate: dict) -> float:
    """Round-trip commission in bps of notional."""
    if symbol in C.CRYPTO:
        return 2 * C.CRYPTO_COMMISSION_SIDE * 1e4
    if symbol in C.FX:
        base = BASE_NOTIONAL_CCY[symbol]
        notional = 100_000 * usd_rate.get(base, 1.0)
        return 2 * C.FX_COMMISSION_SIDE_USD_PER_LOT / notional * 1e4
    if symbol in C.METALS:
        return 2 * C.METAL_COMMISSION_SIDE * 1e4
    return 0.0  # indices, energy, softs: commission 0 per specs


def lot_table(prices_today: dict, usd_rate: dict) -> pd.DataFrame:
    """Per-symbol: notional per 1.0 lot (USD), per volume_step, volume_min."""
    s = _load_specs()
    out = {}
    for sym in C.UNIVERSE:
        t = TICKER.get(sym, sym)
        if t in s.index:
            row = s.loc[t]
            csize = float(str(row["contract_size"]).split()[0])
            vmin, vstep = float(row["volume_min"]), float(row["volume_step"])
        else:
            csize = {"US500": 1, "US30": 1, "GER40": 1, "BTCUSD": 1, "ETHUSD": 1}.get(sym, np.nan)
            vmin = vstep = 0.01
        p = prices_today.get(sym, np.nan)
        if sym in C.FX:
            base = BASE_NOTIONAL_CCY[sym]
            lot_usd = csize * usd_rate.get(base, 1.0)
        else:
            lot_usd = csize * p
        out[sym] = dict(lot_usd=lot_usd, step_usd=lot_usd * vstep,
                        min_usd=lot_usd * vmin, vmin=vmin, vstep=vstep)
    return pd.DataFrame(out).T
