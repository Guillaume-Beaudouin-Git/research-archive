"""
Handler for regime-filter hypotheses (HMM, VIX threshold, trend/flat classifier).
Classifies hypotheses that condition an existing signal on a detected market regime,
requiring both IC-conditional-on-regime and regime-stability checks at Level A.
"""
from .base import HypothesisHandler


class RegimeFilterHandler(HypothesisHandler):
    @classmethod
    def classify(cls, promising_md_path: str) -> bool: ...
    def run_level_A(self) -> dict: ...
    def run_level_B(self) -> dict: ...
    def run_level_C(self) -> dict: ...
    def generate_report(self) -> str: ...
