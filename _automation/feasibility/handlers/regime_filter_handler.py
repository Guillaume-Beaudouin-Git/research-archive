"""
Handler for regime-filter hypotheses (HMM, VIX threshold, trend/flat classifier).
Classifies hypotheses that condition an existing signal on a detected market regime,
requiring both IC-conditional-on-regime and regime-stability checks at Level A.
"""
from __future__ import annotations

import re
from datetime import date

from .base import HypothesisHandler

_REGIME_PATTERNS: list[str] = [
    r"hidden markov",
    r"markov switching",
    r"VIX threshold",
    r"VIX.{0,10}filter",
    r"regime.adaptive",
    r"regime.detect",
    r"regime.filter",
    r"regime.{0,15}signal",
    r"market regime",
    r"rethinking trend following.*optimal regime",
    r"optimal regime.depend",
    r"surfing.*equity curve|equity curve.*surf",
    r"trend.follow.*switch|switch.*trend.follow",
    r"equity curve.*trend.*filter|trend.*filter.*equity curve",
    r"AI.*forex.*LLM.*regime|LLM.*regime.*label",
]

_REQUIRES_HUMAN_REASON = (
    "RegimeFilterHandler is not yet implemented. "
    "Regime-conditional strategies require: (1) a regime classifier trained strictly "
    "in-sample within each WF fold (no look-ahead), (2) a regime-stability check "
    "(low switching frequency), and (3) IC-conditional-on-regime analysis. "
    "Estimated effort: 2 days."
)


class RegimeFilterHandler(HypothesisHandler):
    """Handler for regime-filter / HMM / VIX-threshold hypotheses (stub)."""

    @classmethod
    def classify(cls, promising_md_path: str) -> bool:
        """Return True if .md mentions regime detection, HMM, or VIX threshold terminology."""
        try:
            text = open(promising_md_path, encoding="utf-8").read()
        except OSError:
            return False
        return any(re.search(p, text, re.IGNORECASE) for p in _REGIME_PATTERNS)

    def run_level_A(self) -> dict:
        result = {
            "verdict": "REQUIRES_HUMAN",
            "category": "REGIME_FILTER",
            "reason": _REQUIRES_HUMAN_REASON,
            "pass": False,
        }
        self.results["level_A"] = result
        return result

    def run_level_B(self) -> dict:
        result = {"pass": False, "skipped": True, "reason": "Level A = REQUIRES_HUMAN"}
        self.results["level_B"] = result
        return result

    def run_level_C(self) -> dict:
        result = {"pass": False, "skipped": True, "reason": "Level A = REQUIRES_HUMAN"}
        self.results["level_C"] = result
        return result

    def generate_report(self) -> str:
        source_name = self.promising_md_path.split("/")[-1]
        run_date = str(date.today())
        lines = [
            "# Feasibility Report: Regime Filter Handler",
            "",
            f"**Date**: {run_date}",
            f"**Source**: `{source_name}`",
            "**Handler**: RegimeFilterHandler",
            "**Category**: REGIME_FILTER",
            "**Overall Verdict**: **REQUIRES_HUMAN**",
            "",
            "---",
            "",
            "## Niveau A — Hypothesis Classification",
            "",
            "**Verdict**: REQUIRES_HUMAN",
            f"**Reason**: {_REQUIRES_HUMAN_REASON}",
            "",
            "---",
            "",
            "## Niveau B — Walk-Forward Backtest",
            "",
            "*(Level B skipped — REQUIRES_HUMAN)*",
            "",
            "---",
            "",
            "## Niveau C — Sanity Checks",
            "",
            "*(Level C skipped — REQUIRES_HUMAN)*",
            "",
            "---",
            "",
            "## Recommendation",
            "",
            "**REQUIRES_HUMAN** — Implement by: "
            "(1) building a `RegimeClassifier` class that fits strictly in-sample "
            "within each WF fold (HMM / VIX threshold / trend filter), "
            "(2) passing the regime mask to `vol_target_positions` as a position multiplier "
            "(0 = off, 1 = on), "
            "(3) adding a regime-stability check (min regime duration > 5 bars), "
            "(4) comparing IC-in-regime vs IC-unconditional via Level A delta-IC gate. "
            "Note: regime filters interact with the 3-modification cap on Strategy A.",
            "",
            "---",
            "*Generated by RegimeFilterHandler (stub) · Awaiting implementation*",
        ]
        return "\n".join(lines)
