"""
Handler for exit-rule modification hypotheses on existing validated strategies.
Classifies hypotheses that propose TP/SL/time-stop rule changes on Strategy A, B, or C
without altering the core entry signal (max 3 modifications total, lesson 10).
"""
from __future__ import annotations

import re
from datetime import date

from .base import HypothesisHandler

_EXIT_PATTERNS: list[str] = [
    r"trailing stop",
    r"take.?profit",
    r"\bTP.{0,5}SL\b",
    r"\bSL.{0,5}TP\b",
    r"time.?stop",
    r"exit rule",
    r"stop.?loss rule",
    r"profit target",
    r"target.*exit",
    r"intraday.*trend.*manage|manage.*intraday.*trend",
    r"how to manage.*trend trade",
]

_REQUIRES_HUMAN_REASON = (
    "ExitRuleHandler is not yet implemented. "
    "Exit-rule modifications require strategy-specific logic (different for A/B/C) "
    "and a position-level P&L simulation rather than portfolio-level vol-targeting. "
    "Estimated effort to implement: 1 day per strategy."
)


class ExitRuleHandler(HypothesisHandler):
    """Handler for TP/SL/time-stop exit-rule modification hypotheses (stub)."""

    @classmethod
    def classify(cls, promising_md_path: str) -> bool:
        """Return True if .md mentions TP/SL, trailing stop, or exit-rule terminology."""
        try:
            text = open(promising_md_path, encoding="utf-8").read()
        except OSError:
            return False
        return any(re.search(p, text, re.IGNORECASE) for p in _EXIT_PATTERNS)

    def run_level_A(self) -> dict:
        result = {
            "verdict": "REQUIRES_HUMAN",
            "category": "EXIT_RULE",
            "reason": _REQUIRES_HUMAN_REASON,
            "pass": False,
        }
        self.results["level_A"] = result
        return result

    def run_level_B(self) -> dict:
        result = {"pass": False, "skipped": True, "reason": "Level A = REQUIRES_HUMAN"}
        self.results["level_B"] = result
        return result

    def run_level_C(self) -> dict:
        result = {"pass": False, "skipped": True, "reason": "Level A = REQUIRES_HUMAN"}
        self.results["level_C"] = result
        return result

    def generate_report(self) -> str:
        source_name = self.promising_md_path.split("/")[-1]
        run_date = str(date.today())
        lines = [
            "# Feasibility Report: Exit Rule Handler",
            "",
            f"**Date**: {run_date}",
            f"**Source**: `{source_name}`",
            "**Handler**: ExitRuleHandler",
            "**Category**: EXIT_RULE",
            "**Overall Verdict**: **REQUIRES_HUMAN**",
            "",
            "---",
            "",
            "## Niveau A — Hypothesis Classification",
            "",
            "**Verdict**: REQUIRES_HUMAN",
            f"**Reason**: {_REQUIRES_HUMAN_REASON}",
            "",
            "---",
            "",
            "## Niveau B — Walk-Forward Backtest",
            "",
            "*(Level B skipped — REQUIRES_HUMAN)*",
            "",
            "---",
            "",
            "## Niveau C — Sanity Checks",
            "",
            "*(Level C skipped — REQUIRES_HUMAN)*",
            "",
            "---",
            "",
            "## Recommendation",
            "",
            "**REQUIRES_HUMAN** — To implement this handler, build a position-level P&L simulator "
            "that applies TP/SL/time-stop rules to each individual trade generated by Strategy A/B/C's "
            "entry signal. Then compare aggregate Sharpe and MaxDD vs the no-exit baseline. "
            "This must be strategy-specific (Strategy C NQ uses $400 SL cap, different from Strategy A's "
            "portfolio vol-target). Counts toward the 3-modification cap per strategy.",
            "",
            "---",
            "*Generated by ExitRuleHandler (stub) · Awaiting implementation*",
        ]
        return "\n".join(lines)
