"""
Handler for exit-rule modification hypotheses on existing validated strategies.
Classifies hypotheses that propose TP/SL/time-stop rule changes on Strategy A, B, or C
without altering the core entry signal (max 3 modifications total, lesson 10).
"""
from .base import HypothesisHandler


class ExitRuleHandler(HypothesisHandler):
    @classmethod
    def classify(cls, promising_md_path: str) -> bool: ...
    def run_level_A(self) -> dict: ...
    def run_level_B(self) -> dict: ...
    def run_level_C(self) -> dict: ...
    def generate_report(self) -> str: ...
