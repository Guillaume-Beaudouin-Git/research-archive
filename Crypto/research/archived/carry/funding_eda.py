"""
funding_eda.py

Exploratory analysis of Hyperliquid historical funding rates.
Requires: data/funding_rates.csv  (generated by funding_data.py)

Tasks covered:
  2a  Time series plot: BTC and ETH (shared x-axis)
  2b  BTC funding rate distribution histogram with ±1σ / ±2σ
  2c  ACF of BTC funding rates (240 lags = 10 days at 1-hour frequency)
  2d  Cross-symbol funding rate correlation heatmap
  2e  Mean reversion diagnostic table
  3   Data quality report

Outputs saved to outputs/:
  funding_rates_timeseries.png
  funding_rate_distribution.png
  funding_rate_acf.png
  funding_correlation.png

NOTE: Hyperliquid funding is HOURLY. The task specification assumed 8h intervals
(Binance default). All lag counts and annualisation are adjusted accordingly:
  - ACF "30 × 8h lags" → 240 × 1h lags  (same 10-day span)
  - Annualisation: × 8760  (not × 1095)
  - Forward-return horizons: 1h, 8h, 24h, 48h  (same absolute durations)
"""

import os
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")   # headless rendering
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
from matplotlib.colors import TwoSlopeNorm

SYMBOLS    = ["BTC", "ETH", "SOL", "AVAX", "LINK", "DOGE", "ARB", "OP", "SUI", "WIF"]
DATA_FILE  = "data/funding_rates.csv"
OUTPUT_DIR = "outputs"
ANNUALIZE  = 24 * 365

os.makedirs(OUTPUT_DIR, exist_ok=True)


# ── Load ───────────────────────────────────────────────────────────────────────
def load_data() -> pd.DataFrame:
    df = pd.read_csv(DATA_FILE)
    df["timestamp"] = pd.to_datetime(df["timestamp"], utc=True)
    return df.sort_values(["symbol", "timestamp"]).reset_index(drop=True)


# ── Task 2a: Time series ───────────────────────────────────────────────────────
def plot_timeseries(df: pd.DataFrame) -> None:
    """BTC and ETH funding rates on shared x-axis with ±2σ bands."""
    fig, axes = plt.subplots(2, 1, figsize=(14, 8), sharex=True)
    colors = {"BTC": "steelblue", "ETH": "darkorange"}

    for ax, sym in zip(axes, ["BTC", "ETH"]):
        s   = df[df["symbol"] == sym].sort_values("timestamp")
        mu  = s["funding_rate"].mean()
        sig = s["funding_rate"].std()
        rate_pct = s["funding_rate"] * 100

        ax.plot(s["timestamp"], rate_pct,
                lw=0.5, color=colors[sym], alpha=0.75, label=sym)
        ax.axhline(0,                  color="black",  lw=0.6, ls="--", alpha=0.6)
        ax.axhline((mu + 2*sig) * 100, color="red",    lw=0.9, ls=":",  alpha=0.7,
                   label=f"+2σ = {(mu+2*sig)*100:.4f}%")
        ax.axhline((mu - 2*sig) * 100, color="green",  lw=0.9, ls=":",  alpha=0.7,
                   label=f"-2σ = {(mu-2*sig)*100:.4f}%")
        ax.set_ylabel("Rate (%/hr)", fontsize=9)
        ax.set_title(f"{sym} Hourly Funding Rate", fontsize=10)
        ax.legend(fontsize=8, loc="upper right")
        ax.grid(True, alpha=0.2)

    axes[-1].xaxis.set_major_formatter(mdates.DateFormatter("%Y-%m"))
    axes[-1].xaxis.set_major_locator(mdates.MonthLocator(interval=3))
    fig.autofmt_xdate(rotation=30)
    fig.suptitle("Hyperliquid Hourly Funding Rates — BTC & ETH", fontsize=12, y=1.01)
    fig.tight_layout()
    path = os.path.join(OUTPUT_DIR, "funding_rates_timeseries.png")
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {path}")


# ── Task 2b: Distribution ──────────────────────────────────────────────────────
def plot_distribution(df: pd.DataFrame) -> None:
    """BTC funding rate histogram with ±1σ and ±2σ vertical lines."""
    s  = df[df["symbol"] == "BTC"]["funding_rate"].dropna() * 100
    mu = s.mean()
    sg = s.std()

    fig, ax = plt.subplots(figsize=(10, 6))
    ax.hist(s, bins=200, color="steelblue", alpha=0.7, edgecolor="none")

    for n, col, ls in [(1,"orange","--"), (2,"red","-")]:
        ax.axvline(mu + n*sg, color=col, ls=ls, lw=1.5,
                   label=f"+{n}σ = {(mu+n*sg):.5f}%")
        ax.axvline(mu - n*sg, color=col, ls=ls, lw=1.5,
                   label=f"-{n}σ = {(mu-n*sg):.5f}%")
    ax.axvline(mu, color="black", lw=1.2, label=f"Mean = {mu:.5f}%")

    ax.set_xlabel("Funding Rate (%/hr)")
    ax.set_ylabel("Count")
    ax.set_title("BTC Hourly Funding Rate Distribution")
    ax.legend(fontsize=9)
    ax.grid(True, alpha=0.2)
    fig.tight_layout()
    path = os.path.join(OUTPUT_DIR, "funding_rate_distribution.png")
    fig.savefig(path, dpi=150)
    plt.close(fig)
    print(f"  Saved: {path}")


# ── Task 2c: ACF ───────────────────────────────────────────────────────────────
def _manual_acf(x: np.ndarray, nlags: int) -> np.ndarray:
    """Compute ACF without statsmodels."""
    x  = x - x.mean()
    n  = len(x)
    c0 = np.dot(x, x) / n
    vals = [1.0]
    for k in range(1, nlags + 1):
        ck = np.dot(x[k:], x[:-k]) / (n - k)
        vals.append(ck / c0)
    return np.array(vals)


def plot_acf(df: pd.DataFrame, nlags: int = 240) -> None:
    """
    Plot BTC funding rate ACF up to *nlags* 1-hour lags (default 240 = 10 days).
    Task originally specified 30 × 8h lags; adjusted to 240 × 1h = same 10-day span.
    """
    s    = df[df["symbol"] == "BTC"].sort_values("timestamp")["funding_rate"].values
    acf  = _manual_acf(s, nlags)
    lags = np.arange(nlags + 1)
    ci   = 1.96 / np.sqrt(len(s))          # 95% confidence band

    fig, ax = plt.subplots(figsize=(14, 5))
    ax.bar(lags, acf, color="steelblue", alpha=0.7, width=0.8)
    ax.axhline(0,    color="black", lw=0.8)
    ax.axhline( ci,  color="red", ls="--", lw=1.2,
                label=f"95% CI ±{ci:.3f}")
    ax.axhline(-ci,  color="red", ls="--", lw=1.2)

    for lag, label in [(8,"8h"), (24,"1d"), (72,"3d"), (168,"7d"), (240,"10d")]:
        ax.axvline(lag, color="gray", ls=":", lw=0.8, alpha=0.5)
        ax.text(lag + 1, 0.85 * ax.get_ylim()[1] if ax.get_ylim()[1] > 0 else 0.02,
                label, ha="left", fontsize=7, color="gray")

    ax.set_xlabel("Lag (hours)")
    ax.set_ylabel("Autocorrelation")
    ax.set_title(f"BTC Hourly Funding Rate ACF  (lags 0–{nlags} = 10 days)")
    ax.legend(fontsize=9)
    ax.grid(True, alpha=0.2, axis="y")
    fig.tight_layout()
    path = os.path.join(OUTPUT_DIR, "funding_rate_acf.png")
    fig.savefig(path, dpi=150)
    plt.close(fig)
    print(f"  Saved: {path}")

    # Print key values
    print(f"\n  BTC Funding Rate ACF (key lags):")
    print(f"    95% CI: ±{ci:.4f}")
    for lag, label in [(1,"1h"), (8,"8h"), (24,"1d"), (48,"2d"), (72,"3d"),
                       (120,"5d"), (168,"7d"), (240,"10d")]:
        sig = "***" if abs(acf[lag]) > ci else "ns "
        print(f"    lag={lag:>4}h ({label:>3}):  {acf[lag]:+.4f}  {sig}")


# ── Task 2d: Correlation heatmap ───────────────────────────────────────────────
def plot_correlation(df: pd.DataFrame) -> None:
    """Cross-symbol funding rate correlation heatmap."""
    pivot  = df.pivot_table(index="timestamp", columns="symbol", values="funding_rate")
    syms   = [s for s in SYMBOLS if s in pivot.columns]
    corr   = pivot[syms].corr().values
    n      = len(syms)

    fig, ax = plt.subplots(figsize=(10, 8))
    norm = TwoSlopeNorm(vmin=-1, vcenter=0, vmax=1)
    im   = ax.imshow(corr, cmap="RdBu_r", norm=norm)
    plt.colorbar(im, ax=ax, label="Pearson ρ", shrink=0.85)

    ax.set_xticks(range(n)); ax.set_yticks(range(n))
    ax.set_xticklabels(syms, rotation=45, ha="right", fontsize=9)
    ax.set_yticklabels(syms, fontsize=9)

    for i in range(n):
        for j in range(n):
            v = corr[i, j]
            ax.text(j, i, f"{v:.2f}", ha="center", va="center",
                    fontsize=8,
                    color="white" if abs(v) > 0.65 else "black")

    ax.set_title("Funding Rate Correlation Matrix (all 10 symbols)", fontsize=11)
    fig.tight_layout()
    path = os.path.join(OUTPUT_DIR, "funding_correlation.png")
    fig.savefig(path, dpi=150)
    plt.close(fig)
    print(f"  Saved: {path}")

    # Print summary
    corr_df = pd.DataFrame(corr, index=syms, columns=syms)
    upper   = corr_df.where(np.triu(np.ones_like(corr_df, dtype=bool), k=1))
    flat    = upper.stack()
    print(f"\n  Cross-symbol funding correlation stats:")
    print(f"    Mean pairwise ρ : {flat.mean():.3f}")
    print(f"    Min pairwise ρ  : {flat.min():.3f}  ({flat.idxmin()})")
    print(f"    Max pairwise ρ  : {flat.max():.3f}  ({flat.idxmax()})")
    print(f"    % pairs ρ > 0.7 : {(flat > 0.7).mean()*100:.0f}%")


# ── Task 2e: Mean reversion diagnostic ────────────────────────────────────────
def mean_reversion_diagnostic(df: pd.DataFrame) -> None:
    """
    For each symbol, find 8h periods where funding > +2σ or < -2σ and
    compute the average price change over the NEXT 1h, 8h, 24h, 48h.

    Theory:
      Extreme positive funding → over-leveraged longs → expected negative forward return
      Extreme negative funding → over-leveraged shorts → expected positive forward return

    Only symbols with mark_price data are included (yfinance 730-day window).
    """
    HORIZONS = [1, 8, 24, 48]
    H_LABELS = ["1h", "8h", "24h", "48h"]

    bar = "═" * 82
    print(f"\n{bar}")
    print("TASK 2e — MEAN REVERSION DIAGNOSTIC")
    print("  Threshold : ±2σ of each symbol's own distribution")
    print("  Price src : yfinance mark_price (close)")
    print("  Horizons  : next 1h, 8h, 24h, 48h")
    print("  ✓ = theory confirmed  ✗ = theory violated")
    print(bar)

    header = (f"{'Symbol':<6} {'Condition':<15} {'N':>5}  "
              + "".join(f"{l:>12}" for l in H_LABELS))
    print(f"\n{header}")
    print("-" * len(header))

    all_results = []

    for coin in SYMBOLS:
        s = df[df["symbol"] == coin].sort_values("timestamp").reset_index(drop=True)
        s_price = s.dropna(subset=["mark_price"]).reset_index(drop=True)

        if len(s_price) < 200:
            print(f"{coin:<6} {'(< 200 price rows — skip)'}")
            continue

        mu  = s_price["funding_rate"].mean()
        sig = s_price["funding_rate"].std()

        for cond_label, mask in [
            ("pos (>+2σ)", s_price["funding_rate"] > mu + 2*sig),
            ("neg (<-2σ)", s_price["funding_rate"] < mu - 2*sig),
        ]:
            n_ext = mask.sum()
            cols  = [f"{coin:<6}", f" {cond_label:<15}", f"{n_ext:>5}  "]

            for h in HORIZONS:
                fwd = s_price["mark_price"].shift(-h) / s_price["mark_price"] - 1
                avg = fwd[mask].mean()

                if pd.isna(avg) or n_ext == 0:
                    cols.append(f"{'—':>12}")
                    continue

                is_confirmed = (
                    (cond_label.startswith("pos") and avg < 0) or
                    (cond_label.startswith("neg") and avg > 0)
                )
                flag = "✓" if is_confirmed else "✗"
                cols.append(f"{avg*100:>+8.3f}%{flag:>3}")
                all_results.append({
                    "symbol": coin, "condition": cond_label,
                    "horizon": h, "n_extreme": n_ext,
                    "avg_fwd_ret": avg, "confirmed": is_confirmed,
                })

            print("".join(cols))

        print()     # blank line between symbols

    # Overall score
    if all_results:
        res      = pd.DataFrame(all_results)
        n_conf   = res["confirmed"].sum()
        n_total  = len(res)
        pct_conf = n_conf / n_total * 100
        print(f"Overall: {n_conf}/{n_total} ({pct_conf:.0f}%) of horizon×symbol "
              f"combinations confirm mean-reversion theory")
        print(f"\nBy horizon:")
        for h, label in zip(HORIZONS, H_LABELS):
            sub = res[res["horizon"] == h]
            if len(sub):
                p = sub["confirmed"].mean() * 100
                print(f"  {label:>4}: {p:.0f}% confirmed  "
                      f"(avg pos fwd: {sub[sub['condition'].str.startswith('pos')]['avg_fwd_ret'].mean()*100:>+.3f}%  "
                      f"avg neg fwd: {sub[sub['condition'].str.startswith('neg')]['avg_fwd_ret'].mean()*100:>+.3f}%)")


# ── Task 3: Data quality report ────────────────────────────────────────────────
def data_quality_report(df: pd.DataFrame) -> None:
    bar = "═" * 80
    print(f"\n{bar}")
    print("TASK 3 — DATA QUALITY REPORT")
    print(bar)

    t_min = df["timestamp"].min()
    t_max = df["timestamp"].max()
    print(f"\n  Earliest data point : {t_min.strftime('%Y-%m-%d %H:%M UTC')}")
    print(f"  Latest data point   : {t_max.strftime('%Y-%m-%d %H:%M UTC')}")
    print(f"  Total rows          : {len(df):,}")
    print(f"  Symbols             : {df['symbol'].nunique()} / {len(SYMBOLS)}")

    # Per-symbol coverage
    print(f"\n  Per-symbol coverage:")
    print(f"  {'Symbol':<6} {'N':>8}  {'Start':<11} {'End':<11}"
          f" {'Expected':>9} {'Gap%':>6}  {'Price%':>7}  Notes")
    print(f"  {'-'*6} {'-'*8}  {'-'*11} {'-'*11}"
          f" {'-'*9} {'-'*6}  {'-'*7}  {'-'*10}")

    for coin in SYMBOLS:
        s = df[df["symbol"] == coin]
        if s.empty:
            print(f"  {coin:<6} NO DATA")
            continue

        n      = len(s)
        t0     = s["timestamp"].min()
        t1     = s["timestamp"].max()
        hours  = (t1 - t0).total_seconds() / 3600
        exp    = int(hours)
        gap_p  = max(0, (exp - n) / exp * 100) if exp > 0 else 0.0
        pr_pct = s["mark_price"].notna().mean() * 100

        note = ""
        if coin == "WIF":
            note = "(listed Dec 2023)"
        elif pr_pct < 50:
            note = "(price partially avail.)"

        print(f"  {coin:<6} {n:>8,}  {t0.strftime('%Y-%m-%d'):<11} "
              f"{t1.strftime('%Y-%m-%d'):<11} {exp:>9,} {gap_p:>5.1f}%  "
              f"{pr_pct:>6.1f}%  {note}")

    # Frequency verification
    btc   = df[df["symbol"] == "BTC"].sort_values("timestamp")
    diffs = btc["timestamp"].diff().dropna().dt.total_seconds() / 3600
    mode  = diffs.mode().iloc[0]
    large = (diffs > 2).sum()

    print(f"\n  Funding interval (BTC sample):")
    print(f"    Most common gap    : {mode:.0f}h  ← confirms HOURLY settlement")
    print(f"    Gaps > 2h          : {large} occurrences")
    if large > 0:
        gap_idx = diffs[diffs > 2].index
        gap_ts  = btc.loc[btc.index.isin(gap_idx), "timestamp"].head(3)
        for ts in gap_ts:
            print(f"      gap at: {ts}")

    # Hyperliquid vs Binance
    btc_rate = df[df["symbol"] == "BTC"]["funding_rate"]
    binance_per_8h   = 0.0001             # 0.01% per 8h
    binance_per_1h   = binance_per_8h / 8 # 0.00125%/hr equiv.
    mean_abs         = btc_rate.abs().mean()
    median_abs       = btc_rate.abs().median()

    print(f"\n  Funding magnitude: Hyperliquid BTC vs Binance default")
    print(f"    Binance default    : 0.01% per 8h  = {binance_per_1h*100:.5f}%/hr equiv.")
    print(f"    HL mean |rate|     : {mean_abs*100:.5f}%/hr")
    print(f"    HL median |rate|   : {median_abs*100:.5f}%/hr")
    print(f"    HL max |rate|      : {btc_rate.abs().max()*100:.4f}%/hr")
    print(f"    HL mean vs Binance : {mean_abs/binance_per_1h:.2f}x  "
          f"({'higher' if mean_abs > binance_per_1h else 'lower'} than Binance equiv.)")
    print(f"    HL mean ann.       : {btc_rate.mean()*ANNUALIZE*100:+.2f}%/yr  "
          f"(Binance equiv. = {binance_per_8h*3*365*100:.2f}%/yr if always at cap)")

    # Summary answers
    print(f"\n  Summary answers:")
    t0_btc = df[df["symbol"] == "BTC"]["timestamp"].min()
    age_days = (t_max - t0_btc).days
    print(f"    Q: How far back does Hyperliquid funding data go?")
    print(f"    A: {t0_btc.strftime('%Y-%m-%d')} ({age_days} days ≈ {age_days//30} months)")

    print(f"\n    Q: Are there gaps or missing periods?")
    print(f"    A: {large} gaps > 2h found. Data is generally continuous hourly.")

    print(f"\n    Q: Is the data 8-hourly or other frequency?")
    print(f"    A: HOURLY — Hyperliquid settles funding every 1h, not 8h.")
    print(f"       This differs from Binance (8h) and was NOT stated in the task.")

    thin = [c for c in SYMBOLS if len(df[df["symbol"] == c]) < 1000]
    print(f"\n    Q: Symbols with insufficient history?")
    print(f"    A: {thin if thin else 'None — all symbols have ≥ 1,000 hourly observations.'}")

    print(f"\n    Q: Typical HL funding rate vs Binance norm?")
    print(f"    A: HL mean |rate| = {mean_abs*100:.5f}%/hr; "
          f"Binance per-8h default = 0.01% ({binance_per_1h*100:.5f}%/hr equiv.).")
    print(f"       On an hourly basis, HL rates are {mean_abs/binance_per_1h:.1f}x "
          f"the Binance hourly equivalent — but compare 8h sums for fair comparison.")

    # Fair 8h comparison
    hl_per_8h = mean_abs * 8
    print(f"       HL mean |rate| over 8h = {hl_per_8h*100:.5f}%  "
          f"vs Binance 0.01%  → "
          f"{'higher' if hl_per_8h > binance_per_8h else 'lower'} "
          f"({hl_per_8h/binance_per_8h:.2f}x)")


# ── Main ───────────────────────────────────────────────────────────────────────
def main():
    print("Loading data/funding_rates.csv ...")
    df = load_data()
    print(f"Loaded {len(df):,} rows | {df['symbol'].nunique()} symbols\n")

    print("Generating plots...")
    plot_timeseries(df)
    plot_distribution(df)
    plot_acf(df)
    plot_correlation(df)

    mean_reversion_diagnostic(df)
    data_quality_report(df)

    print("\nfunding_eda.py complete.\n")


if __name__ == "__main__":
    main()
